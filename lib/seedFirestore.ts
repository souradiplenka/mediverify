/**
 * Seeds Firestore with sample medicines if empty, or forces reseed if force=true.
 */
export async function seedMedicinesToFirestore(force = false): Promise<{ success: boolean; count: number; message: string }> {
  try {
    const medRef = collection(db, 'medicines');
    if (!force) {
      const q = query(medRef, limit(1));
      const snap = await getDocs(q);
      if (!snap.empty) {
        return { success: true, count: snap.size, message: 'Database already has medicines.' };
      }
    }

    const batch = writeBatch(db);
    SAMPLE_MEDICINES.forEach((med) => {
      // Use batch_number as document ID or auto-generate
      const docRef = doc(medRef, med.batch_number);
      batch.set(docRef, { ...med, id: med.batch_number });
    });

    await batch.commit();
    return { success: true, count: SAMPLE_MEDICINES.length, message: `Successfully seeded ${SAMPLE_MEDICINES.length} medicines to Firebase Firestore.` };
  } catch (error: any) {
    console.error('Error seeding Firestore medicines:', error);
    return { success: false, count: 0, message: error?.message || 'Failed to seed Firestore medicines.' };
  }
}
